local M = {}
function M.run(stage)
  local lines = {"Hera API audit v38; stage=" .. stage}
  local missing, nonfunction = 0, 0
  for _, row in ipairs(entries) do
    local module = package.loaded[row[1]]
    local kind = "MODULE_NOT_LOADED"
    if module ~= nil then
      local ok, value = pcall(function() return module[row[2]] end)
      kind = ok and type(value) or "LOOKUP_ERROR"
      if kind == "nil" then missing = missing + 1 end
      if row[3] and kind ~= "function" then nonfunction = nonfunction + 1 end
    end
    lines[#lines + 1] = row[1] .. "." .. row[2] .. "=" .. kind .. (row[3] and "; direct-call" or "; reference")
  end
  lines[#lines + 1] = "nil=" .. missing .. "; direct-call nonfunction=" .. nonfunction
  local file, err = io.open("Logs/Hera_API_Audit_v38.txt", "a")
  if not file then error(err) end
  file:write(table.concat(lines, "\n") .. "\n\n")
  file:close()
  require("hera_boot").note("API AUDIT " .. stage .. ": nil=" .. missing .. "; direct-call nonfunction=" .. nonfunction, true)
end
return M
